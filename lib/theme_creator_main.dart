      const Color(0xFFBD93F9),
      const Color(0xFFFF79C6),
      const Color(0xFF88C0D0),
      Colors.white,
    ];

    return Padding(
      padding: const EdgeInsets.only(bottom: 12.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(width: 14, height: 14, decoration: BoxDecoration(color: currentColor, borderRadius: BorderRadius.circular(3), border: Border.all(color: Colors.white30))),
              const SizedBox(width: 8),
              Text(label, style: const TextStyle(color: Colors.white, fontSize: 12, fontWeight: FontWeight.bold)),
              const Spacer(),
              Text("#${currentColor.value.toRadixString(16).substring(2).toUpperCase()}", style: const TextStyle(color: Colors.grey, fontSize: 10, fontFamily: 'monospace')),
            ],
          ),
          const SizedBox(height: 6),
          Wrap(
            spacing: 4,
            runSpacing: 4,
            children: sampleSwatches.map((c) {
              final isSelected = currentColor.value == c.value;
              return GestureDetector(
                onTap: () => onColorChanged(c),
                child: Container(
                  width: 20,
                  height: 20,
                  decoration: BoxDecoration(
                    color: c,
                    shape: BoxShape.circle,
                    border: isSelected ? Border.all(color: Colors.white, width: 2) : Border.all(color: Colors.black45),
                  ),
                ),
              );
            }).toList(),
          ),
        ],
      ),
    );
  }
