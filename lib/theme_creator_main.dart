  Widget _buildPresetChip(String label, Color bg, Color header, Color surface, Color pri, Color sec, Color ter) {
    return ActionChip(
      backgroundColor: surface,
      side: BorderSide(color: pri),
      label: Text(label, style: TextStyle(color: pri, fontSize: 10, fontWeight: FontWeight.bold)),
      onPressed: () => _applyPreset(bg, header, surface, pri, sec, ter),
    );
  }

  Widget _buildColorPicker(String label, Color currentColor, Function(Color) onColorChanged) {
    final List<Color> sampleSwatches = [
      const Color(0xFF0B0C10),
      const Color(0xFF10131B),
      const Color(0xFF121622),
      const Color(0xFF4DEAEA),
      const Color(0xFF2196F3),
      const Color(0xFF00FF66),
